/**
 * Playbook operativo: técnicas SEO/GEO que deben guiar CADA propuesta.
 */
function cw_seo_mexico_ai_seo_geo_playbook(): string
{
    return <<<'TXT'
=== PLAYBOOK SEO + GEO (obligatorio en toda propuesta) ===
Aplica siempre — también en diseño, copy, FAQs y CTAs. No es opcional.

SEO (orgánico / nacional)
- Intención de búsqueda clara (informacional / comercial / transaccional); un H1 = una intención.
- Title ~50–60 chars con keyword principal + marca; meta description ~140–160 con beneficio y CTA suave.
- Jerarquía H1→H2→H3 semántica; sin H1 duplicados; sin keyword stuffing.
- E-E-A-T: experiencia real ConlineWeb México, sin inventar clientes, precios ni resultados.
- Enlaces internos a hubs/servicios/blog relacionados (clusters); anclas naturales.
- Canonical correcta; index,follow salvo páginas que deban noindex.
- Schema cuando aplique (Service, FAQPage, Organization/LocalBusiness, Article).
- Mobile-first, CWV (LCP/CLS/INP), HTML semántico, accesibilidad básica.
- Discovery: URL en /indice/, sitemaps y llms tras publicar.

GEO (local / México)
- Ciudad/estado/región en title/H1/body cuando la página es local; NAP consistente (cw-nap).
- Diferenciar ciudad vs estado homónimo; shorts legacy → 301 a canónica larga salvo fases short_urls_fase1–4.
- URLs cortas comerciales (checklist): /mexico/{plaza}/servicios/{svc}/ indexables con contenido único vs hub largo.
- Calendario fases: F1 23-jul–31-ago-2026 · F2 1-sep–15-oct · F3 16-oct–15-dic · F4 16-dic–31-ene-2027 (opcional).
- Propuestas kind short_url_commercial; cron encola; aprobación humana; medir GSC entre fases.
- Señales locales: “en [plaza]”, zona/economía real, servicio × región sin canibalizar.
- Plazas prioridad y hubs México como anclas de cluster local.
- Evitar contenido genérico “México” en páginas de ciudad; personalizar plaza.

Calidad de copy SEO
- Beneficio + prueba + siguiente paso; español México; PyME/empresa.
- FAQ orientadas a queries reales; CTAs claros (WhatsApp/cotizar) sin spam.
- Diseño al servicio del SEO: hero legible, CTAs visibles, sin diluir el mensaje.

Fundamento mínimo en cada propuesta
- Keyword/intención objetivo · por qué mejora el ranking o la conversión local · URL afectada.
=== FIN PLAYBOOK ===
TXT;
}

/**
 * Brief editorial para artículos de blog: valor real al lector + estrategia SEO/GEO.
 * Inyectar en propose_blog, blog_improve, autonomía y draft_blog.
 */
function cw_seo_mexico_ai_blog_editorial_brief(): string
{
    return <<<'TXT'
=== BLOG EDITORIAL (obligatorio: lector primero + SEO) ===
Cada artículo debe ser contenido que una PyME en México QUIERA leer completo — no relleno para Google.

Valor al lector (prioridad)
- Resolver un problema real, responder una duda concreta o enseñar algo aplicable hoy.
- Gancho claro en las primeras líneas: qué aprenderá y por qué le importa (sin clickbait).
- Estructura escaneable: H2/H3 útiles, párrafos cortos, listas/checklists cuando ayuden.
- Ejemplos prácticos México (PyME, operación diaria, decisiones de negocio); sin casos inventados.
- Profundidad útil (700–1200 palabras): cada sección aporta algo nuevo; cero relleno ni repetición.
- Tono experto pero humano: como un consultor que explica bien, no un manual genérico.
- FAQ al final con preguntas que la gente busca de verdad (People Also Ask / conversación real).
- CTA suave al final (cotizar/WhatsApp) solo después de haber entregado valor.

Estrategia SEO/GEO (al servicio del contenido)
- Una intención de búsqueda principal + keyword en title/H1/excerpt de forma natural.
- Cluster de la categoría: enlaces internos a hubs mexico/, servicios y artículos relacionados.
- excerpt y rationale deben explicar: (a) qué gana el lector y (b) qué tráfico/intención SEO persigue.
- Meta útil para CTR: beneficio concreto, no solo keyword stuffing.
- Fortalecer E-E-A-T: experiencia ConlineWeb, criterio profesional, sin estadísticas falsas.

Rehab blog (cerebro · cola separada)
- ~684 templates en noindex / fuera de sitemap hasta rehabilitar.
- Plan por tandas: 2/día Lun–Vie; el cerebro habilita solo la tanda del día en Monitor → «Rehab blog».
- No mezclar con propuestas automáticas. Ejecución IA manual + aprobación humana.
- Tras rehab: quality standard|gold + regenerar sitemap-blog.

Prohibido
- Artículos genéricos copiables de cualquier blog, listas vacías, párrafos que no dicen nada.
- Optimizar solo para robots: si un humano no lo leería, reescribir.
=== FIN BLOG EDITORIAL ===
TXT;
}

